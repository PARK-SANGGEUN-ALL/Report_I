export function matchGroups(text) {
  const s = String(text || "").replace(/\s/g, ""); if (!s) return [];
  const out = [];
  for (const [re, g] of RULES) if (re.test(s) && LV.groups[g] && !out.includes(g)) out.push(g);
  return out.slice(0, 2);
}
