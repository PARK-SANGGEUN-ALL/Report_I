export function redactPII(text, realName, realSchool) {
  if (!text) return text;
  let out = String(text);
  if (realName && realName.trim().length >= 2) {
    out = out.split(realName.trim()).join(PII_PLACEHOLDER_NAME);
  }
  if (realSchool && realSchool.trim().length >= 2) {
    out = out.split(realSchool.trim()).join(PII_PLACEHOLDER_SCHOOL);
  }
  return out;
}

