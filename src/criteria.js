function hasBatchim(ch) {
  if (!ch) return false;
  const code = ch.charCodeAt(0);
  if (code < 0xAC00 || code > 0xD7A3) return null; // 한글 음절 아님 — 판단 불가
  return (code - 0xAC00) % 28 !== 0;
}
const PARTICLE_RULES = [
  { withB: "은", noB: "는" },
  { withB: "이", noB: "가" },
  { withB: "을", noB: "를" },
  { withB: "과", noB: "와" },
  { withB: "이라", noB: "라" },
];
function fixKoreanParticles(text, name) {
  if (!text || !name) return text;
  const lastCh = name[name.length - 1];
  const code = lastCh.charCodeAt(0);
  if (code < 0xAC00 || code > 0xD7A3) return text; // 한글 음절 아니면 교정 불가, 그대로 둠
  const batchimIdx = (code - 0xAC00) % 28;
  const hasB = batchimIdx !== 0;
  const isRieul = batchimIdx === 8; // ㄹ받침 — "으로"가 아니라 "로"를 씀
  const escapedName = name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  let out = text;
  for (const { withB, noB } of PARTICLE_RULES) {
    const wrong = hasB ? noB : withB;
    const correct = hasB ? withB : noB;
    if (wrong === correct) continue;
    out = out.replace(new RegExp(escapedName + wrong, "g"), name + correct);
  }
  // 으로/로 (ㄹ받침 예외 처리)
  const wantRo = !hasB || isRieul;
  out = out.replace(new RegExp(escapedName + (wantRo ? "으로" : "로"), "g"), name + (wantRo ? "로" : "으로"));
  return out;
}

