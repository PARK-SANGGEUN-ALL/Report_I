// 대학명 매칭 헬퍼 — 앱 내 대학명 표기가 약간 다를 수 있어 별칭 매핑
const UNIV_ALIAS = {
  "한국외대": "한국외국어대", "한국외국어대학교": "한국외국어대",
  "이화여대": "이화여자대", "이화여자대학교": "이화여자대",
  "숙명여대": "숙명여자대", "성신여대": "성신여자대",
  "서울시립대학교": "서울시립대", "서울대학교": "서울대", "연세대학교": "연세대",
  "고려대학교": "고려대", "성균관대학교": "성균관대", "한양대학교": "한양대",
  "중앙대학교": "중앙대", "경희대학교": "경희대", "서강대학교": "서강대",
};
function normUniv(name) {
  if (!name) return name;
  const n = String(name).trim();
  return UNIV_ALIAS[n] || n;
}

// 실제 데이터 기반 계열별(인문/자연) 중위 컷 조회. 없으면 null 반환(폴백 사용).
export function getRealCut(univName, gyeol) {
  const n = normUniv(univName);
  const rec = REAL_IPGYEOL_MAIN[n];
  if (!rec) return null;
  const g = (gyeol === "자연") ? "자연" : "인문";
  return rec[g] || null;
}

// 의치한약수 실제 컷 조회 (구분: 의예과/치의예과/한의예과/약학과/수의예과)
export function getRealMedCut(univName, gubun) {
  const n = normUniv(univName);
  const rec = REAL_IPGYEOL_MED[n];
  if (!rec) return null;
  return rec[gubun] || rec[gubun + "(인문)"] || null;
}
